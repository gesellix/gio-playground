#!/usr/bin/env bash
# Checks what a build put into its package, without running it:
#
#   scripts/check-build.sh FILE GIO
#
# FILE is an .apk (needs aapt2 of the Android SDK, ANDROID_HOME), a Windows
# .exe (needs python3) or a macOS or iOS .app (needs plutil, so macOS).
# GIO is the build: fork and diag take the complete platform files of
# platform/ (version 2.0.0, the key PlaygroundPlatformFile, the backup and
# the second activity on Android, the privacy manifest and iOS 15.0 on iOS),
# upstream lets gogio generate them.
set -euo pipefail

file=${1:?usage: $0 FILE GIO}
gio=${2:?usage: $0 FILE GIO}
export GIO=$gio
. "$(dirname "$0")/lib.sh"
complete=no
completefiles && complete=yes

fail=0
check() { # description, ok (yes/no)
	if [ "$2" = yes ]; then echo "[PASS] $1"; else echo "[FAIL] $1"; fail=1; fi
}
is() { if [ "$1" = "$2" ]; then echo yes; else echo no; fi; }
has() { if grep -q -F -- "$2" <<<"$1"; then echo yes; else echo no; fi; }
not() { if [ "$1" = yes ]; then echo no; else echo yes; fi; }

apk() {
	local aapt manifest badging
	aapt=$(find "$ANDROID_HOME/build-tools" -name aapt2 -type f | sort -V | tail -n 1)
	badging=$("$aapt" dump badging "$file")
	manifest=$("$aapt" dump xmltree "$file" --file AndroidManifest.xml)
	echo "$badging" | head -n 1
	check "URL scheme $URL_SCHEME declared" "$(has "$manifest" "\"$URL_SCHEME\"")"
	if [ $complete = yes ]; then
		check "version 2.0.0 (7) from platform/AndroidManifest.xml" "$(has "$badging" "versionCode='7' versionName='2.0.0'")"
		check "allowBackup off" "$(has "$manifest" 'allowBackup(0x01010280)=false')"
		check "SecondActivity declared" "$(has "$manifest" 'gioplayground.SecondActivity')"
	else
		check "version generated by gogio, not 2.0.0" "$(not "$(has "$badging" "versionName='2.0.0'")")"
		check "no SecondActivity (upstream cannot declare it)" "$(not "$(has "$manifest" 'gioplayground.SecondActivity')")"
	fi
}

exe() {
	local found
	found=$(python3 - "$file" <<-'EOF'
		import sys
		data = open(sys.argv[1], "rb").read()
		for s in ("2.0.0.7", "PlaygroundPlatformFile", "FileVersion"):
		    print(s, s.encode("utf-16-le") in data)
	EOF
	)
	echo "$found"
	check "version resource" "$(has "$found" 'FileVersion True')"
	if [ $complete = yes ]; then
		check "version 2.0.0.7 and PlaygroundPlatformFile from platform/winres.json" \
			"$(is "$(grep -c ' True' <<<"$found")" 3)"
	else
		check "no PlaygroundPlatformFile (generated by gogio)" "$(has "$found" 'PlaygroundPlatformFile False')"
	fi
}

plist() { plutil -extract "$2" raw -o - "$1" 2>/dev/null || echo "not set"; }

app() {
	local info
	if [ -f "$file/Contents/Info.plist" ]; then
		info=$file/Contents/Info.plist
		echo "macOS app: $(plist "$info" CFBundleExecutable) $(plist "$info" CFBundleShortVersionString)"
		check "URL scheme $URL_SCHEME" "$(is "$(plist "$info" CFBundleURLTypes.0.CFBundleURLSchemes.0)" "$URL_SCHEME")"
		if [ $complete = yes ]; then
			check "executable ${APP_NAME}Exe from platform/Info_macos.plist" "$(is "$(plist "$info" CFBundleExecutable)" "${APP_NAME}Exe")"
			check "version 2.0.0" "$(is "$(plist "$info" CFBundleShortVersionString)" 2.0.0)"
			check "key PlaygroundPlatformFile" "$(not "$(is "$(plist "$info" PlaygroundPlatformFile)" "not set")")"
		else
			check "executable named by gogio" "$(not "$(is "$(plist "$info" CFBundleExecutable)" "${APP_NAME}Exe")")"
		fi
		return
	fi
	info=$file/Info.plist
	echo "iOS app: $(plist "$info" CFBundleExecutable) $(plist "$info" CFBundleShortVersionString), MinimumOSVersion $(plist "$info" MinimumOSVersion)"
	check "scene manifest" "$(not "$(is "$(plutil -extract UIApplicationSceneManifest json -o - "$info" 2>/dev/null || echo "not set")" "not set")")"
	check "URL scheme $URL_SCHEME" "$(is "$(plist "$info" CFBundleURLTypes.0.CFBundleURLSchemes.0)" "$URL_SCHEME")"
	if [ $complete = yes ]; then
		check "MinimumOSVersion 15.0 from platform/Info_ios.plist" "$(is "$(plist "$info" MinimumOSVersion)" 15.0)"
		check "privacy manifest in the bundle" "$(is "$([ -f "$file/PrivacyInfo.xcprivacy" ] && echo yes)" yes)"
		check "key PlaygroundPlatformFile" "$(not "$(is "$(plist "$info" PlaygroundPlatformFile)" "not set")")"
	else
		check "MinimumOSVersion 13.0, gogio's default" "$(is "$(plist "$info" MinimumOSVersion)" 13.0)"
		check "no privacy manifest" "$(not "$([ -f "$file/PrivacyInfo.xcprivacy" ] && echo yes || echo no)")"
	fi
}

echo "== $file ($gio)"
case $file in
*.apk) apk ;;
*.exe) exe ;;
*.app | *.app/) app ;;
*)
	echo "unknown kind of file: $file" >&2
	exit 2
	;;
esac
exit $fail
